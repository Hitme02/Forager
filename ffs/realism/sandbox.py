"""Tier-B sandbox: the isolated range the live agent harness is allowed to touch.

Tier B is the external-validity layer where the *same* MVT scheduler drives a real,
tool-executing agent loop instead of a simulator. That makes isolation a correctness
requirement of the experiment, not just a courtesy: the only defensible target for an
automated attack agent is a deliberately-vulnerable range with **no network egress** to
anything the operator is not authorised to test. This module owns that guarantee.

Two backends implement one `Sandbox` contract:

- `MockSandbox` -- in-process, no Docker, no sockets. It is the default and the one the
  tests and the headline sweep run on. It is a faithful *model* of the range (per-service
  access hazard + diminishing-value artifact collection, with latency and burstiness), so
  the whole scheduler->harness->grounded-progress pipeline is exercised end to end here and
  in CI without a container runtime or any live traffic. This mirrors how the project
  already gates heavy externals (Numba `cudasim` for CUDA, the serial fallback for MPI,
  the headless shim for NASim).

- `DockerSandbox` -- the real range. It brings up the `docker/` compose fixture on an
  *internal* Docker network (no gateway => no egress), asserts that isolation before any
  action is permitted, and exposes each container service as a `ServiceModel` the harness
  drives over localhost only. It is gated behind an explicit opt-in (see `run_tierb.py
  --live`) and the authorisation acknowledgement documented in `TIERB.md`.

`assert_isolated()` is the single chokepoint. The harness calls it before every action; a
sandbox that cannot prove isolation raises and the run stops. There is deliberately no flag
to relax this.
"""

from __future__ import annotations

import abc

import numpy as np

from .services import DiminishingService, FootholdService, ServiceModel


class IsolationError(RuntimeError):
    """Raised when a sandbox cannot prove it is isolated (no egress). Never caught."""


class Sandbox(abc.ABC):
    """A set of attackable services the harness may touch, plus an isolation guarantee."""

    @abc.abstractmethod
    def assert_isolated(self) -> None:
        """Prove the range has no egress to unauthorised systems, or raise IsolationError.

        Called before *every* agent action. Must be cheap and must fail closed."""

    @abc.abstractmethod
    def services(self) -> list[ServiceModel]:
        """The services exposed on the range; each becomes one foraging branch."""

    @abc.abstractmethod
    def flag_captured(self) -> bool:
        """Has the designated crown-jewel artifact been read (grounded), ending the run?"""

    def teardown(self) -> None:
        """Release range resources (containers, sockets). Default: nothing to do."""


class MockSandbox(Sandbox):
    """In-process model of the range. No Docker, no sockets -- isolation is trivially true.

    The range is `n_services` services. A configurable fraction hold the crown-jewel artifact
    (`flag_services`); reading any one of them captures the flag and meets the objective. Each
    service's difficulty (compute to gain access) is drawn log-normal with the heterogeneity
    knob `sigma` and its MEAN HELD FIXED -- heterogeneity, not abundance, exactly as in the
    abstract surface. `regime` selects the within-branch return shape under test:

      "diminishing" -- after access, the service yields a decreasing sequence of artifacts
                       (juicy ones first): a saturating per-branch value curve. This is the
                       property MVT needs; the prediction is MVT > tuned-fixed at high sigma.
      "constant"    -- each service is a single uniform-value foothold (constant-hazard
                       access, flat post-access value): the NASim-style regime where
                       abandoning buys little and a tuned fixed timeout ties MVT.

    This is the live analogue of the simulator's heterogeneity sweep, and lets Tier B test
    the SAME transfer-boundary hypothesis with real agent-harness mechanics.
    """

    def __init__(self, *, n_services: int = 40, flag_services: int = 2,
                 sigma: float = 0.8, regime: str = "diminishing",
                 mean_A: float = 100.0, mean_tau: float = 25.0, tau_coupling: float = 0.5,
                 tau_spread: float = 0.2, mean_access_cost: float = 10.0,
                 burst_p: float = 1.0, seed: int = 0) -> None:
        if regime not in ("diminishing", "constant"):
            raise ValueError(f"unknown regime: {regime!r}")
        rng = np.random.default_rng(seed)
        # Richness A_i, time-constants tau_i and recon priors are generated by the SAME
        # convention as simulator.heterogeneity.make_surface, so the live range is the
        # faithful analogue of the abstract surface, not a different distribution:
        #   - A_i log-normal with the MEAN HELD FIXED (heterogeneity != abundance);
        #   - tau_i partly coupled to A_i (richer branches mature proportionally slower) and
        #     partly independent -- the coupling is what makes the optimal LEAVING TIME vary
        #     widely across branches, so no single fixed timeout fits them all and MVT's
        #     per-branch rule pays off;
        #   - prior_score a noisy, order-preserving-ish signal of A_i (the scheduler never
        #     sees A_i directly).
        if sigma == 0.0:
            A = np.full(n_services, mean_A, dtype=float)
        else:
            mu = np.log(mean_A) - 0.5 * sigma**2
            A = np.exp(mu + sigma * rng.standard_normal(n_services))
            A *= mean_A / A.mean()
        coupled = mean_tau * (A / mean_A)
        independent = np.exp(np.log(mean_tau) - 0.5 * tau_spread**2
                             + tau_spread * rng.standard_normal(n_services))
        tau = np.clip(tau_coupling * coupled + (1.0 - tau_coupling) * independent, 1.0, None)
        prior = A * np.exp(-0.5 * 0.4**2 + 0.4 * rng.standard_normal(n_services))

        flag_idx = set(rng.choice(n_services, size=min(flag_services, n_services),
                                  replace=False).tolist())
        self._services: list[ServiceModel] = []
        for i in range(n_services):
            holds_flag = i in flag_idx
            if regime == "diminishing":
                svc: ServiceModel = DiminishingService(
                    service_id=i, A=float(A[i]), tau=float(tau[i]), holds_flag=holds_flag,
                    burst_p=burst_p, seed=seed * 1000 + i, prior=float(prior[i]))
            else:
                # constant-hazard access: heterogeneous expected effort, mean held fixed
                cost_i = mean_access_cost * (A[i] / mean_A)
                svc = FootholdService(
                    service_id=i, access_cost=float(cost_i), holds_flag=holds_flag,
                    burst_p=burst_p, seed=seed * 1000 + i)
            self._services.append(svc)

    def assert_isolated(self) -> None:
        # An in-process model issues no network traffic at all: isolation is definitional.
        return None

    def services(self) -> list[ServiceModel]:
        return self._services

    def flag_captured(self) -> bool:
        return any(s.flag_read for s in self._services)


# Default services on the `docker/` compose range: (dns_name, holds_flag). svc3 is the
# crown-jewel. Reachable by container DNS name because the harness runs *on* the internal
# network (see docker/docker-compose.yml and TIERB.md).
_DEFAULT_MANIFEST = [("svc0", False), ("svc1", False), ("svc2", False),
                     ("svc3", True), ("svc4", False), ("svc5", False)]

# Hosts the isolation probe tries to reach. On the internal (no-egress) network every
# connection must FAIL; a success means egress exists and the range is not isolated.
_EGRESS_PROBE = [("1.1.1.1", 53), ("8.8.8.8", 53)]


class DockerSandbox(Sandbox):
    """Real isolated range backed by the `docker/` compose fixture (gated, opt-in).

    The fixture stands up a set of deliberately-vulnerable services on an *internal* Docker
    network (no gateway => no egress). The harness runs *on* that network (as the compose
    `harness` service) and reaches each fixture service by its container DNS name, so no host
    ports are published and the containers remain egress-less.

    `assert_isolated()` verifies isolation from the inside, the strongest check available: it
    attempts to open an outbound connection to a few public hosts and raises if ANY succeeds
    (egress exists). It fails closed -- only an actively-refused/timed-out probe is treated as
    isolated. Requires the operator's authorisation acknowledgement; never the default and not
    exercised by the test suite. It needs no container runtime libraries -- only sockets.
    """

    def __init__(self, compose_project: str = "ffs_tierb", *,
                 network_name: str = "ffs_tierb_isolated",
                 manifest: list | None = None,
                 flag_depth: int = 3, probe_timeout: float = 1.0,
                 acknowledged: bool = False) -> None:
        if not acknowledged:
            raise IsolationError(
                "DockerSandbox requires an explicit authorisation acknowledgement. "
                "Pass acknowledged=True only for an isolated range you are authorised to "
                "test (see TIERB.md); the default experiment uses MockSandbox.")
        self.compose_project = compose_project
        self.network_name = network_name
        self.manifest = manifest or _DEFAULT_MANIFEST
        self.flag_depth = flag_depth
        self.probe_timeout = probe_timeout
        self._services: list[ServiceModel] | None = None

    def assert_isolated(self) -> None:
        """Raise unless an outbound connection to every probe host fails (i.e. no egress)."""
        import socket
        for host, port in _EGRESS_PROBE:
            try:
                with socket.create_connection((host, port), timeout=self.probe_timeout):
                    raise IsolationError(
                        f"egress detected: reached {host}:{port}. The range is NOT isolated; "
                        "refusing to run the agent harness. Use an `internal` Docker network.")
            except OSError:
                continue  # connection refused / timed out => no egress to this host (good)

    def services(self) -> list[ServiceModel]:
        if self._services is None:
            from .services import LiveHttpService  # lazy: needs the live fixture
            self.assert_isolated()
            self._services = []
            for i, entry in enumerate(self.manifest):
                if isinstance(entry, dict):        # extended manifest (live evaluation)
                    self._services.append(LiveHttpService(
                        i, f"http://{entry['name']}", holds_flag=entry.get("flag", False),
                        max_value=entry.get("max_value", float("inf")),
                        n_art=entry.get("n_art", 32), prior=entry.get("prior", 1.0),
                        foothold_value=entry.get("foothold_value", 10.0)))
                else:
                    name, flag = entry
                    self._services.append(LiveHttpService(i, f"http://{name}",
                                                          holds_flag=flag))
        return self._services

    def flag_captured(self) -> bool:
        return any(s.flag_read for s in (self._services or []))

    def teardown(self) -> None:
        if self._services:
            for s in self._services:
                close = getattr(s, "close", None)
                if close:
                    close()
